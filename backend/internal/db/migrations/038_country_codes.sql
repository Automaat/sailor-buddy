-- Countries become a list of ISO 3166-1 alpha-2 codes on editions
-- (cruises), legs (trips) and voyages, instead of one free-text string
-- spelt differently on each row ("Norwegia", "dania"). An empty list means
-- no countries; the column is never NULL. Each code is two upper-case
-- letters; the app checks it against its list (internal/countries).
--
-- The old text is split on commas, semicolons, slashes, plus signs and
-- spaced dashes, then on " i ", " oraz ", " and " and "&" when a part is
-- not a name by itself ("Bośnia i Hercegowina" stays one country). Each
-- part is matched, ignoring case, accents and punctuation, against the
-- Polish and English CLDR names of every country, its code and a few common
-- aliases. The migration stops on a part it cannot match, naming the row
-- and the value, rather than drop it: fix the value and migrate again.
--
-- The name table below is historical data for this migration only; it is
-- dropped at the end.

CREATE FUNCTION country_key_038(s TEXT) RETURNS TEXT
LANGUAGE sql IMMUTABLE AS $$
    SELECT btrim(regexp_replace(lower(translate(s,
        'ĄĆĘŁŃÓŚŹŻąćęłńóśźżÀÁÂÃÄÅàáâãäåÇçÈÉÊËèéêëÌÍÎÏìíîïÑñÒÔÕÖØòôõöøÙÚÛÜùúûüÝýÿŠšŽžÆæ',
        'ACELNOSZZacelnoszzAAAAAAaaaaaaCcEEEEeeeeIIIIiiiiNnOOOOOoooooUUUUuuuuYyySsZzAa')),
        '[^a-z0-9]+', ' ', 'g'))
$$;

